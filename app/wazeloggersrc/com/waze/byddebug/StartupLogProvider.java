/**
 * Optional five-minute Waze startup diagnostic injected only when the BYD Multi Patcher
 * troubleshooting toggle is enabled.
 *
 * Privacy design: this logger deliberately does NOT read Waze/general logcat, location,
 * routes, search text, account data, device identifiers, network identifiers, Intent extras,
 * UI text, clipboard, contacts, files, microphone/audio or media. It records only technical
 * startup state generated by this helper itself.
 */
public final class StartupLogProvider extends ContentProvider {
    private static final String TAG = "BYD-Waze-Debug";
    private static final long CAPTURE_MS = 5L * 60L * 1000L;
    private static final long SAMPLE_MS = 5L * 1000L;
    private static final long MAIN_THREAD_TIMEOUT_MS = 1500L;
    private static final AtomicBoolean STARTED = new AtomicBoolean(false);

    @Override public boolean onCreate() {
        final Context context = getContext();
        if (context == null || !STARTED.compareAndSet(false, true)) return true;

        Thread logger = new Thread(new Runnable() {
            @Override public void run() {
                capture(context.getApplicationContext());
            }
        }, "BYD-Waze-StartupDiagnostics");
        logger.setDaemon(true);
        logger.start();
        return true;
    }

    private static void capture(Context context) {
        BufferedWriter writer = null;
        Session session = null;
        long started = android.os.SystemClock.elapsedRealtime();
        try {
            String version = packageVersion(context);
            String model = sanitiseFilePart(Build.MODEL);
            String stamp = new SimpleDateFormat("yyyy-MM-dd_HH-mm-ss", Locale.US).format(new Date());
            String fileName = "Waze-" + sanitiseFilePart(version) + "-debug_" + model + "_" + stamp + ".txt";

            ContentValues values = new ContentValues();
            values.put(MediaStore.MediaColumns.DISPLAY_NAME, fileName);
            values.put(MediaStore.MediaColumns.MIME_TYPE, "text/plain");
            values.put(MediaStore.MediaColumns.RELATIVE_PATH,
                    Environment.DIRECTORY_DOWNLOADS + "/BYD-Multi-Patcher");
            Uri outputUri = context.getContentResolver().insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values);
            if (outputUri == null) throw new IllegalStateException("Could not create Downloads diagnostic file");

            OutputStream stream = context.getContentResolver().openOutputStream(outputUri, "w");
            if (stream == null) throw new IllegalStateException("Could not open Downloads diagnostic file");
            writer = new BufferedWriter(new OutputStreamWriter(
                    stream, java.nio.charset.StandardCharsets.UTF_8), 16 * 1024);

            writeHeader(context, writer, version, fileName);
            writer.flush();

            session = new Session(context, writer, started);
            session.installHooks();
            session.event("DIAGNOSTIC STARTED");

            long nextSample = started;
            while (android.os.SystemClock.elapsedRealtime() - started < CAPTURE_MS) {
                long now = android.os.SystemClock.elapsedRealtime();
                if (now >= nextSample) {
                    session.sample();
                    nextSample = now + SAMPLE_MS;
                }
                long remaining = CAPTURE_MS - (android.os.SystemClock.elapsedRealtime() - started);
                if (remaining <= 0) break;
                try {
                    Thread.sleep(Math.min(500L, remaining));
                } catch (InterruptedException interrupted) {
                    Thread.currentThread().interrupt();
                    break;
                }
            }

            session.event("CAPTURE COMPLETE elapsed_ms="
                    + (android.os.SystemClock.elapsedRealtime() - started));
            Log.i(TAG, "Privacy-safe Waze startup diagnostic saved as " + fileName);
        } catch (Throwable error) {
            Log.e(TAG, "Startup diagnostics failed", error);
            if (session != null) {
                session.internalError("LOGGER ERROR", error);
            } else if (writer != null) {
                try {
                    writer.write("\n===== LOGGER ERROR =====\n");
                    writer.write(error.getClass().getName());
                    writer.newLine();
                    writer.flush();
                } catch (Throwable ignored) {}
            }
        } finally {
            if (session != null) session.close();
            if (writer != null) {
                try { writer.close(); } catch (Throwable ignored) {}
            }
        }
    }

    private static void writeHeader(Context context, BufferedWriter writer, String version,
                                    String fileName) throws Exception {
        DisplayMetrics dm = context.getResources().getDisplayMetrics();
        writer.write("BYD Multi Patcher - Waze " + version + " privacy-safe troubleshooting log");
        writer.newLine();
        writer.write("Capture duration: up to 5 minutes from Waze process startup");
        writer.newLine();
        writer.write("File: " + fileName);
        writer.newLine();
        writer.write("Started UTC: " + utcNow());
        writer.newLine();
        writer.write("Waze version: " + version);
        writer.newLine();
        writer.write("Device model: " + safeTechnical(Build.MANUFACTURER) + " " + safeTechnical(Build.MODEL));
        writer.newLine();
        writer.write("Android: " + safeTechnical(Build.VERSION.RELEASE) + " (API " + Build.VERSION.SDK_INT + ")");
        writer.newLine();
        writer.write("ABIs: " + Arrays.toString(Build.SUPPORTED_ABIS));
        writer.newLine();
        writer.write("Display: " + dm.widthPixels + "x" + dm.heightPixels
                + " px, density=" + dm.density + ", densityDpi=" + dm.densityDpi
                + ", scaledDensity=" + dm.scaledDensity);
        writer.newLine();
        writer.write("WebView provider: " + webViewProvider());
        writer.newLine();
        writer.write("Privacy: this logger does NOT read or record Waze/general logcat, GPS/location, routes/destinations, searches, account/user data, contacts, messages, clipboard, microphone/audio, photos/files, Android/device IDs, serial numbers, advertising IDs, network names, IP/MAC addresses, Intent contents or UI text.");
        writer.newLine();
        writer.write("Recorded technical data only: app/activity lifecycle, non-text UI structure counts, main-thread responsiveness, memory pressure, Waze/Android/device-model/display/WebView versions and crash stack frames without exception messages.");
        writer.newLine();
        writer.write("No telemetry is uploaded by this logger. The file is written locally to Downloads/BYD-Multi-Patcher.");
        writer.newLine();
        writer.write("================================================================");
        writer.newLine();
    }

    private static final class Session {
        private final Context context;
        private final BufferedWriter writer;
        private final long started;
        private final Handler mainHandler = new Handler(Looper.getMainLooper());
        private final AtomicBoolean closed = new AtomicBoolean(false);
        private final AtomicBoolean crashRecorded = new AtomicBoolean(false);
        private volatile WeakReference<Activity> resumedActivity = new WeakReference<>(null);
        private Application application;
        private Application.ActivityLifecycleCallbacks lifecycleCallbacks;
        private ComponentCallbacks2 componentCallbacks;
        private SafeCrashHandler crashHandler;

        Session(Context context, BufferedWriter writer, long started) {
            this.context = context;
            this.writer = writer;
            this.started = started;
        }

        void installHooks() {
            Context appContext = context.getApplicationContext();
            if (appContext instanceof Application) {
                application = (Application) appContext;
                lifecycleCallbacks = new Application.ActivityLifecycleCallbacks() {
                    @Override public void onActivityCreated(Activity activity, Bundle state) {
                        event("ACTIVITY created " + activityName(activity)
                                + " state=" + (state == null ? "new" : "restored"));
                    }
                    @Override public void onActivityStarted(Activity activity) {
                        event("ACTIVITY started " + activityName(activity));
                    }
                    @Override public void onActivityResumed(Activity activity) {
                        resumedActivity = new WeakReference<>(activity);
                        event("ACTIVITY resumed " + activityName(activity));
                    }
                    @Override public void onActivityPaused(Activity activity) {
                        event("ACTIVITY paused " + activityName(activity));
                    }
                    @Override public void onActivityStopped(Activity activity) {
                        event("ACTIVITY stopped " + activityName(activity));
                    }
                    @Override public void onActivitySaveInstanceState(Activity activity, Bundle outState) {
                        event("ACTIVITY save-state " + activityName(activity));
                    }
                    @Override public void onActivityDestroyed(Activity activity) {
                        Activity current = resumedActivity.get();
                        if (current == activity) resumedActivity = new WeakReference<>(null);
                        event("ACTIVITY destroyed " + activityName(activity));
                    }
                };
                application.registerActivityLifecycleCallbacks(lifecycleCallbacks);
            }

            componentCallbacks = new ComponentCallbacks2() {
                @Override public void onTrimMemory(int level) {
                    event("MEMORY trim level=" + level);
                }
                @Override public void onLowMemory() {
                    event("MEMORY low-memory callback");
                }
                @Override public void onConfigurationChanged(Configuration newConfig) {
                    event("CONFIGURATION changed (contents intentionally not recorded)");
                }
            };
            context.registerComponentCallbacks(componentCallbacks);
            ensureCrashHandler();
        }

        void sample() {
            if (closed.get()) return;
            ensureCrashHandler();
            sampleMemory();
            sampleMainThreadAndUi();
        }

        private void sampleMemory() {
            try {
                Runtime runtime = Runtime.getRuntime();
                long javaUsed = runtime.totalMemory() - runtime.freeMemory();
                long javaTotal = runtime.totalMemory();
                long javaMax = runtime.maxMemory();
                long nativeUsed = Debug.getNativeHeapAllocatedSize();

                ActivityManager.MemoryInfo info = new ActivityManager.MemoryInfo();
                ActivityManager am = (ActivityManager) context.getSystemService(Context.ACTIVITY_SERVICE);
                if (am != null) am.getMemoryInfo(info);

                event("MEMORY java_used=" + kb(javaUsed)
                        + "KB java_total=" + kb(javaTotal)
                        + "KB java_max=" + kb(javaMax)
                        + "KB native_alloc=" + kb(nativeUsed)
                        + "KB system_avail=" + kb(info.availMem)
                        + "KB low=" + info.lowMemory
                        + " threads=" + Thread.activeCount());
            } catch (Throwable error) {
                internalError("MEMORY SAMPLE ERROR", error);
            }
        }

        private void sampleMainThreadAndUi() {
            final CountDownLatch latch = new CountDownLatch(1);
            final long posted = android.os.SystemClock.elapsedRealtime();
            try {
                mainHandler.post(new Runnable() {
                    @Override public void run() {
                        long latency = android.os.SystemClock.elapsedRealtime() - posted;
                        event("MAIN responsive latency_ms=" + latency);
                        snapshotUi();
                        latch.countDown();
                    }
                });

                if (!latch.await(MAIN_THREAD_TIMEOUT_MS, TimeUnit.MILLISECONDS)) {
                    event("MAIN STALL latency_ms=>" + MAIN_THREAD_TIMEOUT_MS);
                    writeMainThreadStack();
                }
            } catch (InterruptedException interrupted) {
                Thread.currentThread().interrupt();
            } catch (Throwable error) {
                internalError("MAIN SAMPLE ERROR", error);
            }
        }

        private void snapshotUi() {
            Activity activity = resumedActivity.get();
            if (activity == null) {
                event("UI no-resumed-activity");
                return;
            }
            try {
                View decor = activity.getWindow() == null ? null : activity.getWindow().getDecorView();
                if (decor == null) {
                    event("UI activity=" + activityName(activity) + " decor=none");
                    return;
                }
                ViewStats stats = new ViewStats();
                collectViewStats(decor, stats, 0);
                event("UI activity=" + activityName(activity)
                        + " focus=" + decor.hasWindowFocus()
                        + " decor=" + decor.getWidth() + "x" + decor.getHeight()
                        + " visible=" + (decor.getVisibility() == View.VISIBLE)
                        + " hw_accel=" + decor.isHardwareAccelerated()
                        + " views=" + stats.total
                        + " visible_views=" + stats.visible
                        + " laid_out=" + stats.laidOut
                        + " webviews=" + stats.webViews
                        + " surfaces=" + stats.surfaceViews
                        + " textures=" + stats.textureViews
                        + " max_depth=" + stats.maxDepth);
            } catch (Throwable error) {
                internalError("UI SAMPLE ERROR", error);
            }
        }

        private void writeMainThreadStack() {
            try {
                Thread main = Looper.getMainLooper().getThread();
                StackTraceElement[] frames = main.getStackTrace();
                event("MAIN STACK BEGIN frames=" + frames.length);
                int limit = Math.min(frames.length, 80);
                for (int i = 0; i < limit; i++) {
                    event("  at " + safeFrame(frames[i]));
                }
                event("MAIN STACK END");
            } catch (Throwable error) {
                internalError("MAIN STACK ERROR", error);
            }
        }

        private void ensureCrashHandler() {
            try {
                Thread.UncaughtExceptionHandler current = Thread.getDefaultUncaughtExceptionHandler();
                if (current == crashHandler || current instanceof SafeCrashHandler) return;
                if (current == null) return;
                crashHandler = new SafeCrashHandler(this, current);
                Thread.setDefaultUncaughtExceptionHandler(crashHandler);
            } catch (Throwable error) {
                internalError("CRASH HANDLER INSTALL ERROR", error);
            }
        }

        void recordCrash(Thread thread, Throwable throwable) {
            if (!crashRecorded.compareAndSet(false, true)) return;
            event("UNCAUGHT EXCEPTION main_thread=" + (thread == Looper.getMainLooper().getThread()));
            writeThrowableWithoutMessages(throwable);
        }

        private void writeThrowableWithoutMessages(Throwable throwable) {
            int causeDepth = 0;
            Throwable current = throwable;
            while (current != null && causeDepth < 8) {
                event((causeDepth == 0 ? "EXCEPTION " : "CAUSED BY ") + current.getClass().getName());
                StackTraceElement[] frames = current.getStackTrace();
                int limit = Math.min(frames.length, 120);
                for (int i = 0; i < limit; i++) {
                    event("  at " + safeFrame(frames[i]));
                }
                current = current.getCause();
                causeDepth++;
            }
        }

        void internalError(String label, Throwable error) {
            event(label + " type=" + error.getClass().getName());
        }

        void event(String message) {
            if (closed.get()) return;
            synchronized (writer) {
                try {
                    long elapsed = android.os.SystemClock.elapsedRealtime() - started;
                    writer.write(String.format(Locale.US, "+%06dms  %s", elapsed, message));
                    writer.newLine();
                    writer.flush();
                } catch (Throwable ignored) {}
            }
        }

        void close() {
            if (!closed.compareAndSet(false, true)) return;
            try {
                if (application != null && lifecycleCallbacks != null) {
                    application.unregisterActivityLifecycleCallbacks(lifecycleCallbacks);
                }
            } catch (Throwable ignored) {}
            try {
                if (componentCallbacks != null) context.unregisterComponentCallbacks(componentCallbacks);
            } catch (Throwable ignored) {}
            try {
                if (crashHandler != null && Thread.getDefaultUncaughtExceptionHandler() == crashHandler) {
                    Thread.setDefaultUncaughtExceptionHandler(crashHandler.delegate);
                }
            } catch (Throwable ignored) {}
        }
    }

    private static final class SafeCrashHandler implements Thread.UncaughtExceptionHandler {
        private final Session session;
        private final Thread.UncaughtExceptionHandler delegate;

        SafeCrashHandler(Session session, Thread.UncaughtExceptionHandler delegate) {
            this.session = session;
            this.delegate = delegate;
        }

        @Override public void uncaughtException(Thread thread, Throwable throwable) {
            try { session.recordCrash(thread, throwable); } catch (Throwable ignored) {}
            delegate.uncaughtException(thread, throwable);
        }
    }

    private static final class ViewStats {
        int total;
        int visible;
        int laidOut;
        int webViews;
        int surfaceViews;
        int textureViews;
        int maxDepth;
    }

    private static void collectViewStats(View view, ViewStats stats, int depth) {
        if (view == null || stats.total >= 10000) return;
        stats.total++;
        if (view.getVisibility() == View.VISIBLE) stats.visible++;
        if (view.isLaidOut()) stats.laidOut++;
        if (view instanceof WebView) stats.webViews++;
        if (view instanceof SurfaceView) stats.surfaceViews++;
        if (view instanceof TextureView) stats.textureViews++;
        if (depth > stats.maxDepth) stats.maxDepth = depth;
        if (view instanceof ViewGroup) {
            ViewGroup group = (ViewGroup) view;
            int count = group.getChildCount();
            for (int i = 0; i < count; i++) {
                collectViewStats(group.getChildAt(i), stats, depth + 1);
            }
        }
    }

    private static String activityName(Activity activity) {
        if (activity == null) return "none";
        return activity.getClass().getName();
    }

    private static String packageVersion(Context context) {
        try {
            PackageInfo info = context.getPackageManager().getPackageInfo(context.getPackageName(), 0);
            return info.versionName == null ? "unknown" : info.versionName;
        } catch (Throwable ignored) {
            return "unknown";
        }
    }

    private static String webViewProvider() {
        try {
            PackageInfo info = WebView.getCurrentWebViewPackage();
            if (info == null) return "none";
            return safeTechnical(info.packageName) + " " + safeTechnical(info.versionName);
        } catch (Throwable error) {
            return "unavailable:" + error.getClass().getSimpleName();
        }
    }

    private static String safeTechnical(String value) {
        if (value == null) return "unknown";
        return value.replaceAll("[^A-Za-z0-9._+() /-]+", "?");
    }

    private static String sanitiseFilePart(String value) {
        if (value == null || value.trim().isEmpty()) return "unknown";
        String clean = value.trim().replaceAll("[^A-Za-z0-9._-]+", "-");
        return clean.length() > 48 ? clean.substring(0, 48) : clean;
    }

    private static String safeFrame(StackTraceElement frame) {
        if (frame == null) return "unknown";
        StringBuilder out = new StringBuilder();
        out.append(frame.getClassName()).append('.').append(frame.getMethodName());
        String file = frame.getFileName();
        if (file != null) out.append('(').append(file);
        int line = frame.getLineNumber();
        if (line >= 0) out.append(':').append(line);
        if (file != null) out.append(')');
        return out.toString();
    }

    private static long kb(long bytes) {
        return bytes / 1024L;
    }

    private static String utcNow() {
        SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss.SSS'Z'", Locale.US);
        format.setTimeZone(TimeZone.getTimeZone("UTC"));
        return format.format(new Date());
    }

    @Override public Cursor query(Uri uri, String[] projection, String selection,
                                  String[] selectionArgs, String sortOrder) { return null; }
    @Override public String getType(Uri uri) { return null; }
    @Override public Uri insert(Uri uri, ContentValues values) { return null; }
    @Override public int delete(Uri uri, String selection, String[] selectionArgs) { return 0; }
    @Override public int update(Uri uri, ContentValues values, String selection, String[] selectionArgs) { return 0; }
}
